        for (int Inicio = 0; Inicio <= CadenaOrigen.length() - 1; Inicio++) {
            for (TamTrama = 0; TamTrama <= cadena.length() - 1; TamTrama++) {
                if (CadenaOrigen.substring(Inicio, Inicio + 1).equals(cadena.substring(TamTrama, TamTrama + 1))) {
                    Respuesta += cadena1.substring(TamTrama, TamTrama + 1);
                }
            }
        }
        return (Respuesta);
